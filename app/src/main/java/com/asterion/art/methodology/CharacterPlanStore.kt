package com.asterion.art.methodology

import android.content.Context
import com.asterion.art.data.GeneratedImagePublisher
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.security.MessageDigest
import java.util.UUID

data class CharacterPhaseOnePlan(
    val id:String,
    val createdAt:Long,
    val sheets:Int,
    val slots:List<String>,
    val seed:Long,
    val status:String="PENDING",
    val selections:List<CharacterSelection> = emptyList(),
    val frozen:List<FrozenCharacter> = emptyList(),
    val prompts:List<String> = emptyList(),
    val modelId:String?=null,
    val failure:String?=null,
    val authorizedJobId:String?=null,
    val progressStage:String=""
) {
    val total:Int get()=CharacterPhaseOne.count(sheets)
    val ready:Boolean get()=status=="READY"||status=="AUTHORIZED"
    fun assertComplete() {
        require(ready){"Character design has not finished"}
        require(selections.size==total&&frozen.size==total)
        require(prompts.size==sheets)
        require(CharacterSheetCompiler.audit(frozen,sheets).isEmpty()) {
            "Unresolved population collision; all characters must be finalized"
        }
        for(i in 0 until sheets) {
            require(prompts[i]==CharacterSheetCompiler.sheet(
                frozen.subList(i*5,(i+1)*5),i+1)) {
                "Frozen renderer context was modified after certification"
            }
        }
    }
}

/** Exactly one frozen design population per plan, never regenerated by the image worker. */
class CharacterPlanStore(context:Context) {
    private val folder=File(context.applicationContext.filesDir,"character-phase1/plans")
        .also{it.mkdirs()}
    private fun file(id:String):File {
        require(id.matches(Regex("[A-Za-z0-9_-]{8,100}")))
        return File(folder,id+".json")
    }
    @Synchronized fun create(slots:List<String>,sheets:Int,seed:Long):CharacterPhaseOnePlan {
        CharacterPhaseOne.validateSlots(slots)
        CharacterPhaseOne.count(sheets)
        val plan=CharacterPhaseOnePlan(
            UUID.randomUUID().toString(),System.currentTimeMillis(),
            sheets,slots.map{it.trim()},seed)
        persist(plan)
        return plan
    }
    private fun primaryToJson(p:PrimaryConcept)=JSONObject().apply {
        put("slot",p.originalSlot);put("name",p.name)
        put("canonical_id",p.canonicalId?:JSONObject.NULL)
        put("provenance",p.provenance)
    }
    private fun primaryFromJson(v:JSONObject)=PrimaryConcept(
        v.getString("slot"),v.getString("name"),
        v.optString("canonical_id").takeIf{it.isNotBlank()&&it!="null"},
        v.getString("provenance"))
    private fun frozenToJson(d:FrozenCharacter)=JSONObject().apply {
        put("number",d.number)
        put("primary",JSONArray(d.primary.map(::primaryToJson)))
        put("anatomy",d.anatomy)
        put("face_eyes_hair",d.faceEyesHair)
        put("topology",d.topology)
        put("fusion",d.fusion)
        put("materials",d.materials)
        put("differentiation",d.differentiation)
        put("render_description",d.renderDescription)
        put("audit_evidence",d.auditEvidence)
        put("pairwise",JSONArray(d.pairwise.map{pair->
            JSONObject().put("first",pair.first).put("second",pair.second)
                .put("mechanism",pair.mechanism)
        }))
        put("higher_order",d.higherOrder)
    }
    private fun frozenFromJson(d:JSONObject)=FrozenCharacter(
        d.getInt("number"),d.getJSONArray("primary").let{a->
            (0 until a.length()).map{primaryFromJson(a.getJSONObject(it))}
        },d.getString("anatomy"),d.getString("face_eyes_hair"),
        d.getString("topology"),d.getString("fusion"),
        d.getString("materials"),d.getString("differentiation"),
        d.getString("render_description"),d.getString("audit_evidence"),
        d.getJSONArray("pairwise").let{items->
            (0 until items.length()).map {i->
                val item=items.getJSONObject(i)
                PairwisePhysicalFusion(item.getString("first"),
                    item.getString("second"),item.getString("mechanism"))
            }
        },d.optString("higher_order",""))
    @Synchronized fun persist(p:CharacterPhaseOnePlan) {
        if(p.ready)p.assertComplete()
        val data=JSONObject().apply {
            put("schema","asterion.character-phase1.v3")
            put("id",p.id);put("created_at",p.createdAt)
            put("sheets",p.sheets);put("slots",JSONArray(p.slots))
            put("seed",p.seed);put("status",p.status)
            put("selections",JSONArray(p.selections.map{selection->
                JSONObject().put("number",selection.number)
                    .put("primary",JSONArray(selection.concepts.map(::primaryToJson)))
            }))
            put("frozen",JSONArray(p.frozen.map(::frozenToJson)))
            put("sheet_prompts",JSONArray(p.prompts))
            put("model_id",p.modelId?:JSONObject.NULL)
            put("failure",p.failure?:JSONObject.NULL)
            put("progress_stage",p.progressStage.take(200))
            put("authorized_job",p.authorizedJobId?:JSONObject.NULL)
            put("requires_visual_audit",true)
            put("no_template_based_designs",true)
            put("no_design_direction_or_subconcepts",true)
        }
        GeneratedImagePublisher.atomicWrite(file(p.id),
            data.toString(2).toByteArray(Charsets.UTF_8))
    }
    @Synchronized fun load(id:String):CharacterPhaseOnePlan {
        val j=JSONObject(file(id).readText(Charsets.UTF_8))
        require(j.getString("schema")=="asterion.character-phase1.v3")
        fun JSONObject.optional(k:String)=optString(k,"")
            .takeIf{it.isNotBlank()&&it!="null"}
        fun JSONArray.strings()=(0 until length()).map{getString(it)}
        val sel=j.getJSONArray("selections")
        val roster=j.getJSONArray("frozen")
        return CharacterPhaseOnePlan(
            j.getString("id"),j.getLong("created_at"),j.getInt("sheets"),
            j.getJSONArray("slots").strings(),j.getLong("seed"),
            j.getString("status"),
            (0 until sel.length()).map{idx->
                val o=sel.getJSONObject(idx)
                val a=o.getJSONArray("primary")
                CharacterSelection(o.getInt("number"),
                    (0 until a.length()).map{primaryFromJson(a.getJSONObject(it))})
            },(0 until roster.length()).map{frozenFromJson(roster.getJSONObject(it))},
            j.getJSONArray("sheet_prompts").strings(),
            j.optional("model_id"),j.optional("failure"),j.optional("authorized_job"),
            j.optString("progress_stage","")
        )
    }
    /** Recover independent populations after activity/process recreation. */
    @Synchronized fun recent(limit:Int=12):List<CharacterPhaseOnePlan> =
        folder.listFiles().orEmpty()
            .filter { it.isFile && it.extension=="json" }
            .mapNotNull { runCatching { load(it.nameWithoutExtension) }.getOrNull() }
            .sortedByDescending { it.createdAt }
            .take(limit.coerceIn(1,100))

    /**
     * Retry a failed Qwen design without discarding the fully validated
     * identities already frozen in the original durable population.
     */
    @Synchronized fun retryFailed(id:String):CharacterPhaseOnePlan {
        val p=load(id)
        require(p.status=="FAILED"){"Only a failed resolution may be resumed"}
        p.frozen.forEach{it.validate()}
        require(p.frozen.size<=p.total)
        return p.copy(status="PENDING",failure=null,
            progressStage="Resuming after "+p.frozen.size+
                "/"+p.total+" completed character identities").also(::persist)
    }
    @Synchronized fun begin(id:String):CharacterPhaseOnePlan {
        val plan=load(id)
        require(plan.status=="PENDING"||plan.status=="DESIGNING") {
            "Plan has already been finalized or failed"
        }
        return if(plan.status=="DESIGNING")plan
        else plan.copy(status="DESIGNING",
            progressStage="Loading local Qwen3 design model").also(::persist)
    }
    @Synchronized fun stage(id:String,description:String) {
        val p=load(id)
        val summary=description.take(200)
        if(p.status=="DESIGNING" && p.progressStage!=summary)
            persist(p.copy(progressStage=summary))
    }
    @Synchronized fun progress(id:String,
             resolved:List<CharacterSelection>,frozen:List<FrozenCharacter>) {
        val state=load(id)
        require(state.status=="DESIGNING")
        persist(state.copy(selections=resolved,frozen=frozen,
            progressStage="Frozen "+frozen.size+"/"+state.total+
                " anatomical character identities"))
    }
    @Synchronized fun certify(id:String,modelId:String,
        selections:List<CharacterSelection>,designs:List<FrozenCharacter>):CharacterPhaseOnePlan {
        val original=load(id)
        require(original.status=="DESIGNING")
        require(selections.size==original.total&&designs.size==original.total)
        require(CharacterSheetCompiler.audit(designs,original.sheets).isEmpty())
        val sheetPrompts=(1..original.sheets).map{number->
            CharacterSheetCompiler.sheet(
                designs.subList((number-1)*5,number*5),number)
        }
        return original.copy(status="READY",selections=selections,
            frozen=designs,prompts=sheetPrompts,modelId=modelId).also(::persist)
    }
    @Synchronized fun fail(id:String,reason:String) {
        val p=load(id)
        if(p.status=="DESIGNING"||p.status=="PENDING")
            persist(p.copy(status="FAILED",failure=reason.take(2000),
                progressStage="Resolution failed"))
    }
    @Synchronized fun authorize(id:String,jobId:String) {
        val p=load(id)
        p.assertComplete()
        require(p.status=="READY" ||
            (p.status=="AUTHORIZED"&&p.authorizedJobId==jobId)) {
            "Already authorized; use the existing generation job"
        }
        require(jobId.matches(Regex("[A-Za-z0-9_-]{8,100}")))
        persist(p.copy(status="AUTHORIZED",authorizedJobId=jobId))
    }
    fun requireAuthorized(id:String,jobId:String):CharacterPhaseOnePlan {
        val plan=load(id)
        plan.assertComplete()
        require(plan.status=="AUTHORIZED"&&plan.authorizedJobId==jobId) {
            "Generate action was not explicitly authorized for this frozen roster"
        }
        return plan
    }
}
