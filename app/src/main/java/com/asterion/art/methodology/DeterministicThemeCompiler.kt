package com.asterion.art.methodology

import kotlin.random.Random

/**
 * Five grounded, independent text-theme conditioning systems. Uses the real
 * frozen roulette and user parameters, without speculative character content,
 * external network, hidden reasoning or an image-model call.
 */
object DeterministicThemeCompiler {
    private val layouts=listOf(
        "asymmetrically tiered structures with a dominant descending diagonal",
        "radial load paths crossing a protected open central cavity",
        "interlocking folded planes around a vertical spatial spine",
        "a braided horizontal movement axis with suspended branches",
        "two opposing material masses joined by a narrow active threshold")
    fun compile(plan:ThemeTextPlan,atoms:List<String>,index:Int):ThemeText {
        require(index in 0..4 && atoms.size in 3..6)
        val random=Random(plan.seed xor ((index+1)*198491317L))
        val pivot=atoms[random.nextInt(atoms.size)]
        val title=atoms.first().replaceFirstChar{it.uppercase()}+
            " × "+atoms.last().replaceFirstChar{it.uppercase()}+
            " / "+(index+1)+" · "+pivot
        val movement=listOf("compression","torsion","shear","expansion",
            "interleaving")[index]
        val materialTransitions=atoms.mapIndexed { i,atom ->
            val attached=atoms[(i+1)%atoms.size]
            atom+" is a physically visible "+when(i%4) {
                0->"primary structural mass"
                1->"supporting material interface"
                2->"spatial circulation or energy channel"
                else->"contrast-bearing contour boundary"
            }+" whose surface and geometry continuously transition into "+
                attached+" through shared "+movement+" and material gradients"
        }
        val keywords=if(plan.keywords.isEmpty())"No extra owner keywords" else
            "Binding owner keywords: "+plan.keywords.joinToString("; ")
        val intensity="Badassness "+(plan.badassness?.toString()?:"unassigned")+
            "; eroticity "+(plan.eroticity?.toString()?:"unassigned")+
            "; contextual tension "+(plan.tension?.toString()?:"unassigned")+"."
        val extra=plan.extraParameters.entries.joinToString(" ") {
            "Owner parameter "+it.key+": "+it.value+"."
        }
        val visual=buildString {
            append("Independent reusable visual theme T").append(index+1)
            append(". Physical topology: ").append(layouts[index])
            append("; global mass distribution is generated by ").append(movement)
            append(". FROZEN ATOM INTERDEPENDENCE: ")
            append(materialTransitions.joinToString(". ")).append(". ")
            append("All ").append(atoms.size)
            append(" atoms remain explicitly recognizable and jointly necessary; ")
            append("none is a text label, detached decoration, arbitrary ")
            append("character, collage panel or unrelated scenery. ")
            append("Dominant forms stay legible first; detailed material ")
            append("microstructure grows from the same contact surfaces. ")
            append("Foreground, mid-distance and depth share continuous ")
            append("geometry rather than unconnected objects. ")
            append("Use asymmetric negative-space counterweights and ")
            append("directional lighting to clarify support and overlap. ")
            append("Identity-neutral host figures may demonstrate scale ")
            append("without inventing a face, outfit or source character. ")
            append(keywords).append(". ").append(intensity).append(" ")
            plan.characterConfiguration?.let {
                append("Preserve owner character configuration: ").append(it).append(". ")
            }
            plan.liquidDirection?.let {
                append("Liquid parameter: ").append(it).append(". ")
            }
            if(plan.intensityV2.isNotEmpty())append(
                com.asterion.art.engine.CreativeIntensity.description(plan.intensityV2)
            ).append(" ")
            append(extra)
            append(" Camera is subordinate to the fixed atom/material logic, ")
            append("and visual revisions must not replace any frozen atom.")
        }
        return ThemeText("T"+(index+1),title,atoms,visual)
    }
}
