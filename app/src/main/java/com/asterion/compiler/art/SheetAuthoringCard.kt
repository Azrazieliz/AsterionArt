package com.asterion.compiler.art

import android.content.Intent
import androidx.activity.compose.rememberLauncherForActivityResult
import androidx.activity.result.contract.ActivityResultContracts
import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.Row
import androidx.compose.foundation.layout.fillMaxWidth
import androidx.compose.foundation.layout.padding
import androidx.compose.material3.Button
import androidx.compose.material3.Card
import androidx.compose.material3.FilterChip
import androidx.compose.material3.OutlinedButton
import androidx.compose.material3.OutlinedTextField
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateListOf
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.remember
import androidx.compose.runtime.setValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.platform.LocalContext
import androidx.compose.ui.unit.dp
import java.util.UUID

/**
 * A real editable sheet-authoring UI. References remain original bitmap files,
 * structured fields are retained in PNG metadata and a JSON sidecar.
 * It never asks an image model to invent typography or source references.
 */
@Composable
fun SheetAuthoringCard(onCreated: (ReferenceSheet) -> Unit) {
    val context = LocalContext.current
    var opened by remember { mutableStateOf(false) }
    var kind by remember { mutableStateOf(SheetKind.THEME) }
    var title by remember { mutableStateOf("") }
    val fields = remember { mutableStateListOf<SheetField>().apply { addAll(SheetTemplates.fields(kind)) } }
    val images = remember { mutableStateListOf<String>() }
    var status by remember { mutableStateOf("") }
    val picker = rememberLauncherForActivityResult(ActivityResultContracts.OpenMultipleDocuments()) { uris ->
        uris.forEach { uri ->
            runCatching {
                context.contentResolver.takePersistableUriPermission(
                    uri, Intent.FLAG_GRANT_READ_URI_PERMISSION,
                )
            }
            if (uri.toString() !in images) images += uri.toString()
        }
    }
    Card {
        Column(
            modifier = Modifier.fillMaxWidth().padding(16.dp),
            verticalArrangement = Arrangement.spacedBy(9.dp),
        ) {
            Row(horizontalArrangement = Arrangement.spacedBy(10.dp)) {
                Text("Reference sheet builder", modifier = Modifier.weight(1f))
                OutlinedButton(onClick = { opened = !opened }) {
                    Text(if (opened) "Close" else "Create sheet")
                }
            }
            if (opened) {
                Text("Author visual facts and attach your reference images. No autogenerated or inferred content.")
                SheetKind.entries.forEach { choice ->
                    FilterChip(
                        selected = kind == choice,
                        onClick = {
                            kind = choice
                            fields.clear()
                            fields.addAll(SheetTemplates.fields(choice))
                        },
                        label = { Text(choice.name.replace('_', ' ')) },
                    )
                }
                OutlinedTextField(
                    value = title, onValueChange = { title = it },
                    label = { Text("Sheet name") },
                    modifier = Modifier.fillMaxWidth(),
                    singleLine = true,
                )
                fields.forEachIndexed { index, field ->
                    OutlinedTextField(
                        value = field.description,
                        onValueChange = { text -> fields[index] = field.copy(description = text) },
                        label = { Text(field.label) },
                        modifier = Modifier.fillMaxWidth(),
                        minLines = 2,
                    )
                }
                Button(onClick = { picker.launch(arrayOf("image/*")) }) {
                    Text("Choose visual references (" + images.size + ")")
                }
                images.forEachIndexed { index, uri ->
                    Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                        Text(uri.substringAfterLast('/').takeLast(35), modifier = Modifier.weight(1f))
                        OutlinedButton(onClick = { images.removeAt(index) }) { Text("Remove") }
                    }
                }
                val draft = AuthoredSheet(UUID.randomUUID().toString(), kind, title, fields.toList(), images.toList())
                draft.problems().forEach { Text(it) }
                Button(
                    enabled = draft.problems().isEmpty(),
                    modifier = Modifier.fillMaxWidth(),
                    onClick = {
                        runCatching { SheetStudio(context).save(draft) }
                            .onSuccess {
                                onCreated(it)
                                status = "Structured sheet saved with references and machine-readable metadata."
                                opened = false
                                title = ""
                                images.clear()
                                fields.clear()
                                fields.addAll(SheetTemplates.fields(kind))
                            }
                            .onFailure { status = "Sheet creation failed: " + it.message }
                    },
                ) { Text("Save sheet and use in project") }
                if (status.isNotBlank()) Text(status)
            }
        }
    }
}
